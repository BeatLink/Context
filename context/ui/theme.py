_current: Theme | None = None
_installed = False
_provider = None
_user_provider = None
_monitor = None


def current() -> Theme:
    """The loaded theme, read once per run."""
    global _current
    if _current is None:
        _current = Theme.load()
    return _current


def reload() -> Theme:
    global _current
    _current = Theme.load()
    return _current


def install() -> bool:
    """Put the stylesheets on the display, once, and watch style.css.

    Anything using a `ctx-` style class has to call this — the launcher styles
    its rail, the editor its tiles, and whichever appears first must not be the
    unstyled one.

    Both providers sit *above* USER, not at it. GTK4 ignores `gtk-theme-name`,
    so the usual way to get a theme is `~/.config/gtk-4.0/gtk.css` importing it
    — which is what home-manager writes — and GTK loads that file at USER. A
    desktop theme therefore arrives at Context's own priority rather than at
    THEME beneath it, and a rule tied with it is decided by whatever the
    tie-break happens to be. That is not a contest to enter: `.linked` was
    defined, present in the sheet, and silently lost to Mint-Y for exactly this
    reason. The built-in sheet goes one step above the imported theme, and
    style.css one above that, so the order is theme, then Context, then the
    user — which is what it always claimed to be.
    """
    global _installed, _provider, _user_provider
    if _installed:
        return True

    from gi.repository import Gdk, Gtk

    display = Gdk.Display.get_default()
    if display is None:
        return False

    _provider = Gtk.CssProvider()
    _provider.load_from_data(current().css())
    Gtk.StyleContext.add_provider_for_display(
        display, _provider, Gtk.STYLE_PROVIDER_PRIORITY_USER
    )

    _user_provider = Gtk.CssProvider()
    # A mistake in the file should name the line in the log, not vanish.
    _user_provider.connect(
        "parsing-error",
        lambda _p, section, error: log.warning(
            "style.css: %s (%s)", error.message, section.to_string()
        ),
    )
    _load_user_css()
    Gtk.StyleContext.add_provider_for_display(
        display, _user_provider, Gtk.STYLE_PROVIDER_PRIORITY_USER + 1
    )

    _watch()
    _installed = True
    return True


def _load_user_css() -> None:
    _user_provider.load_from_data(style_text().encode())


def _watch() -> None:
    """Re-style on save, the way Hyprland reloads its own config."""
    global _monitor
    from gi.repository import Gio

    gfile = Gio.File.new_for_path(str(style_path()))
    _monitor = gfile.monitor_file(Gio.FileMonitorFlags.NONE, None)
    _monitor.connect("changed", _on_style_changed)


def _on_style_changed(_monitor, _file, _other, event) -> None:
    from gi.repository import Gio

    # Editors save in bursts; the hint is the burst ending. CREATED covers a
    # first save, DELETED an rm — which restores the defaults.
    if event in (
        Gio.FileMonitorEvent.CHANGES_DONE_HINT,
        Gio.FileMonitorEvent.CREATED,
        Gio.FileMonitorEvent.DELETED,
    ):
        log.info("style.css changed; restyling")
        reinstall()


def reinstall() -> bool:
    """Reload both stylesheets in place, for when style.css changes."""
    reload()
    if not _installed:
        return install()
    _provider.load_from_data(current().css())
    _load_user_css()
    return True
