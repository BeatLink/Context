"""Theming.

Context is themed the way the rest of a Hyprland session is: it ships one
stylesheet, and `$XDG_CONFIG_HOME/context/style.css` loads over it — the same
contract as waybar's or swaync's style.css, so the file can be written by hand
or generated by whatever templates the rest of the desktop's colours.

Every colour is published as a `@define-color ctx_*` name and the built-in
rules only ever reference the names, so redefining a few of them recolours the
whole launcher; any ordinary CSS rule in the file styles widgets directly, at
higher priority than the built-in stylesheet. Context also draws things CSS
cannot reach — the app grid's tiles, the layout preview — so it parses the
`@define-color ctx_*` lines out of style.css itself and feeds the same values
to Cairo. The file is watched: saving it restyles the running launcher.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, fields, replace
from pathlib import Path

from context.system.logging_setup import get_logger

log = get_logger("theme")

ENV_STYLE = "CONTEXT_STYLE"


def config_dir() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config")
    return Path(base) / "context"


def style_path() -> Path:
    """The stylesheet the user owns, and the one "write the style file" writes."""
    override = os.environ.get(ENV_STYLE)
    return Path(override) if override else config_dir() / "style.css"


def style_paths() -> list[Path]:
    """Every stylesheet, in the order they are loaded. The last one wins.

    The same chain the settings follow, for the same reason: a NixOS module
    declares a look in /etc/xdg and the user's own file still overrides it. CSS
    needs no merging rule of its own — a later `@define-color` redefinition
    beats an earlier one, which is the behaviour the whole theming contract
    already rests on.
    """
    override = os.environ.get(ENV_STYLE)
    if override:
        return [Path(override)]
    from context.state.settings import system_dirs

    found = [directory / "context" / "style.css" for directory in reversed(system_dirs())]
    found.append(config_dir() / "style.css")
    return found


def style_text() -> str:
    """Every stylesheet that exists, concatenated in load order."""
    parts = []
    for path in style_paths():
        try:
            parts.append(path.read_text())
        except FileNotFoundError:
            continue
        except OSError as exc:
            log.warning("ignoring %s: %s", path, exc)
    return "\n".join(parts)


# One definition per palette entry, tolerant of whatever spacing the file uses.
# Only ctx_* names are Context's to read; a style.css shared with other tools
# may define colours that are not.
_DEFINE = re.compile(r"@define-color\s+ctx_(\w+)\s+([^;\n]+);")


def _rgba(value: str, fallback: tuple[float, float, float, float]):
    """Parse #rgb, #rrggbb, #rrggbbaa, rgb() or rgba() into floats for Cairo."""
    text = value.strip()
    functional = re.fullmatch(r"rgba?\(([^)]*)\)", text)
    if functional:
        parts = [p.strip() for p in functional.group(1).split(",")]
        if len(parts) not in (3, 4):
            return fallback
        try:
            channels = [int(p) / 255 for p in parts[:3]]
            alpha = float(parts[3]) if len(parts) == 4 else 1.0
        except ValueError:
            return fallback
        return (*channels, alpha)

    text = text.lstrip("#")
    try:
        if len(text) == 3:
            parts = [int(c * 2, 16) for c in text]
        elif len(text) in (6, 8):
            parts = [int(text[i : i + 2], 16) for i in range(0, len(text), 2)]
        else:
            return fallback
    except ValueError:
        return fallback
    values = [p / 255 for p in parts]
    while len(values) < 4:
        values.append(1.0)
    return tuple(values[:4])


@dataclass(frozen=True)
class Theme:
    """Colours, as CSS colour strings so style.css and Cairo read the same."""

    accent: str = "#5ac0c0"
    # The card every Context surface is drawn as. Transparency lives here:
    # give it an alpha — `rgba(30, 30, 30, 0.75)` or `#1e1e1ebf` — and the
    # desktop shows through, the same way a bar's stylesheet does it. The
    # window behind the card is transparent already, and nothing else paints
    # the full surface, so the alpha is not compounded.
    surface: str = "#1e1e1e"
    on_surface: str = "#ffffff"

    # Drawn under the surface: the card a group of settings sits on, the line
    # between rows, and the shade a control uses to lift off the background.
    card: str = "#ffffff0d"
    border: str = "#ffffff1a"
    control: str = "#ffffff14"
    control_hover: str = "#ffffff26"

    # Layout preview
    preview_background: str = "#00000047"
    slot_fill: str = "#5ac0c052"
    slot_fill_active: str = "#5ac0c080"
    slot_border: str = "#5ac0c0b3"

    # App grid
    tile_background: str = "#ffffff10"
    tile_hover: str = "#ffffff1f"
    tile_selected: str = "#5ac0c038"

    # The screen a dragged window would land on, and the window on its way out.
    drop_target: str = "#5ac0c024"
    leaving_border: str = "#5ac0c0"

    # Collapsed sidebar. Saved contexts recede, open ones are lit, and the one
    # you are in is ringed — three states that differ in more than shade.
    rail_background: str = "#ffffff08"
    rail_hover: str = "#ffffff24"
    rail_open: str = "#5ac0c033"
    rail_active: str = "#5ac0c059"
    rail_divider: str = "#ffffff26"

    @classmethod
    def load(cls) -> "Theme":
        """The defaults, plus any `@define-color ctx_*` overrides in style.css.

        Only the definitions are read here — the rest of the file is CSS and
        belongs to GTK. A missing or unreadable file means the defaults; a
        garbled line means that line and nothing more.
        """
        legacy = config_dir() / "theme.json"
        if legacy.exists():
            log.warning(
                "theme.json is no longer read; colours now come from %s",
                style_path(),
            )

        text = style_text()
        if not text.strip():
            return cls()

        known = {f.name for f in fields(cls)}
        values = {}
        for name, value in _DEFINE.findall(text):
            if name in known:
                values[name] = value.strip()
            else:
                log.debug("style.css defines unknown colour ctx_%s", name)
        return replace(cls(), **values)

    def write_template(self) -> Path:
        """Write style.css with every colour spelled out, ready to edit."""
        path = style_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "/* Context's colours. Redefine any of these, or add ordinary CSS\n"
            "   rules — this file loads over the built-in stylesheet, the way\n"
            "   waybar's style.css does. Saving it restyles the running\n"
            "   launcher. */\n\n" + self._defines() + "\n"
        )
        return path

    def rgba(self, name: str):
        """One colour as an (r, g, b, a) tuple, for Cairo."""
        default = getattr(Theme(), name, "#ffffff")
        return _rgba(getattr(self, name, default), _rgba(default, (1, 1, 1, 1)))

    def _defines(self) -> str:
        lines = [
            f"@define-color ctx_{f.name} {getattr(self, f.name)};" for f in fields(self)
        ]
        # The surface with its transparency taken off, for the views that cover
        # the whole screen. Derived rather than declared, so a style.css that
        # sets one translucent colour gets both — and it can still be named
        # outright, since a redefinition in that file wins over this.
        red, green, blue, _alpha = self.rgba("surface")
        lines.append(
            "@define-color ctx_surface_solid "
            f"rgb({round(red * 255)}, {round(green * 255)}, {round(blue * 255)});"
        )
        return "\n".join(lines)

    def css(self) -> bytes:
        """The built-in stylesheet.

        Rules reference the `@ctx_*` names rather than inlining values, so a
        redefinition in style.css reaches every rule that uses the colour.
        """
        return (self._defines() + _NAMED_COLORS + _RULES).encode()


# GTK's own named colours, redefined onto the palette.
#
# Setting `gtk-theme-name` or GTK_THEME does not help: the stylesheet is
# already resolved by the time an application can ask, so `theme_bg_color`
# stayed at the desktop theme's value regardless. Every widget Context does not
# name a colour for — scrollbars, popovers, tooltips, menus — reads these, so
# redefining them is what keeps the desktop theme's furniture off Context's
# windows. Measured, not assumed: overriding the names moves the computed
# colour, overriding the setting does not. */
